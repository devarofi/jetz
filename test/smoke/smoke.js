const KEY_RESULTS = 'jetz-smoke-results';
const KEY_PHASE = 'jetz-smoke-phase';
const previousResults = sessionStorage.getItem(KEY_RESULTS) ?? '';
const isReloadPhase = sessionStorage.getItem(KEY_PHASE) === 'reload';
if (!isReloadPhase) sessionStorage.setItem(KEY_PHASE, 'reload');

const results = [];
let currentSection = '';

function section(name) {
	currentSection = name;
	results.push(`# ${name}`);
}

/** Safe one line description of a value for the report (element trees are circular). */
function describe(value) {
	if (value === null) return 'null';
	if (value instanceof JetzElement) return `JetzElement<${value.tagName}>`;
	if (value instanceof State) return `State(${value.getValue()})`;
	if (typeof Node !== 'undefined' && value instanceof Node) return `<${value.nodeName.toLowerCase()}>`;
	if (typeof value === 'function') return `[function ${value.name || 'anonymous'}]`;
	let text;
	try {
		text = JSON.stringify(value) ?? String(value);
	} catch (error) {
		text = String(value);
	}
	text = text.replace(/\s+/g, ' ');
	return text.length > 110 ? `${text.slice(0, 107)}...` : text;
}

function assert(label, actual, expected) {
	const ok = actual === expected;
	results.push(`${ok ? 'PASS' : 'FAIL'} :: ${currentSection} :: ${label} | actual: ${describe(actual)} | expected: ${describe(expected)}`);
}

/** README style comparison (`count.value == 1`), where a state coerces to its value. */
function assertLoose(label, actual, expected) {
	const ok = actual == expected;
	results.push(`${ok ? 'PASS' : 'FAIL'} :: ${currentSection} :: ${label} (loose) | actual: ${describe(String(actual))} | expected: ${describe(String(expected))}`);
}

function finish() {
	const pre = document.createElement('pre');
	pre.id = 'results';
	pre.textContent = [previousResults, results.join('\n')].filter(Boolean).join('\n');
	document.body.appendChild(pre);
	window.__SMOKE_DONE__ = true;
}

const textOf = selector => find(selector).textContent;
const itemsOf = selector => Array.from(findAll(selector)).map(element => element.textContent);

/** Renders a tree into its own container so the sections stay independent. */
function mountInto(name, tree, event) {
	const container = document.createElement('div');
	container.id = `section-${name}`;
	document.body.appendChild(container);
	Jetz.mount(tree, container, event);
	return container;
}

