	classBox.toggleClass('active');
	assert('toggleClass() removes an existing class', find('#utils-classes').className, 'three two');
	classBox.removeClass('three');
	assert('removeClass() removes a class', find('#utils-classes').className, 'two');
	classBox.removeClass('*');
	assert('removeClass("*") clears every class', find('#utils-classes').getAttribute('class'), null);
	classBox.addAttr('title', 'hi');
	assert('addAttr() sets an attribute', classBox.attr('title'), 'hi');
	classBox.removeAttr('title');
	assert('removeAttr() removes an attribute', classBox.attr('title'), null);

	// the utilities work before render too
	const detachedBox = div({ id: 'detached' }, 'detached');
	assert('attr() reads a pending attribute', detachedBox.attr('id'), 'detached');
	detachedBox.setStyle({ color: 'rgb(1, 2, 3)' });
	assert('getStyle() reads a pending style', detachedBox.getStyle('color'), 'rgb(1, 2, 3)');
	mountInto('detached', detachedBox);
	assert('pending attributes are applied on render', find('#detached').getAttribute('id'), 'detached');
	assert('pending styles are applied on render', find('#detached').style.color, 'rgb(1, 2, 3)');

	const idBox = div('id helper').id('late-id');
	mountInto('id-helper', idBox);
	assert('id() sets the id before render', textOf('#late-id'), 'id helper');
	assert('findId() resolves the element by id', idBox.findId('late-id') === idBox, true);

	const textBox = div({ id: 'utils-text' }, 'before');
	mountInto('utils-text', textBox);
	textBox.text('after');
	assert('text() replaces the inner text', textOf('#utils-text'), 'after');

	const emptyBox = div({ id: 'empty-me' }, 'a', 'b');
	mountInto('empty', emptyBox);
	emptyBox.empty();
	assert('empty() clears the children', find('#empty-me').innerHTML, '');
	const removeBox = div({ id: 'remove-me' }, 'bye');
	mountInto('remove', removeBox);
	removeBox.remove();
	assert('remove() detaches the element', find('#remove-me'), null);

	// README: "Utilities"
	section('utilities (html, collection helpers, exports)');

	mountInto('utilities-raw', div({ id: 'raw-box' }, html(`<strong class="raw-strong">raw html</strong>`)));
	assert('html() renders real DOM nodes', textOf('#raw-box strong.raw-strong'), 'raw html');
	assert('range()', JSON.stringify(range(1, 3)), '[1,2,3]');
	assert('flatMap()', JSON.stringify(flatMap([1, [2, [3]], 4])), '[1,2,3,4]');
	assert('createList()', JSON.stringify(createList(3, index => `Item ${index}`)), '["Item 0","Item 1","Item 2"]');
	assert('Array.prototype.last()', [1, 2, 3].last(), 3);
	assert('Array.prototype.take()', JSON.stringify([1, 2, 3].take(2)), '[1,2]');
	assert('Number.prototype.range()', JSON.stringify((3).range(5)), '[3,4,5]');
	assert('html() returns a Raw instance', html('x') instanceof Raw, true);
	assert('createElement() returns a JetzElement', createElement('section', {}, 'x') instanceof JetzElement, true);
	mountInto('create-element', createElement('section', { id: 'made-by-create-element' }, 'custom'));
	assert('createElement() result renders', textOf('#made-by-create-element'), 'custom');

	// README: framework level helpers
	section('framework helpers');

	assert('Jetz.version', Jetz.version, '1.1.1');
	const styleCount = document.head.querySelectorAll('style').length;
	Jetz.style('body { margin: 0 }');
	assert('Jetz.style() injects a style tag', document.head.querySelectorAll('style').length, styleCount + 1);
	const unmountTarget = document.createElement('div');
	document.body.appendChild(unmountTarget);
	Jetz.mount(div('to be cleared'), unmountTarget);
	assert('Jetz.mount() renders into a plain container', unmountTarget.textContent, 'to be cleared');
	Jetz.unmount(unmountTarget);
	assert('Jetz.unmount() clears the container', unmountTarget.innerHTML, '');
	const selectorTarget = document.createElement('div');
	selectorTarget.id = 'unmount-by-selector';
	document.body.appendChild(selectorTarget);
	Jetz.mount(div('selector target'), '#unmount-by-selector');
	assert('Jetz.mount() accepts a selector string', selectorTarget.textContent, 'selector target');
	Jetz.unmount('#unmount-by-selector');
	assert('Jetz.unmount() accepts a selector string', selectorTarget.innerHTML, '');
	let installedPlugin = null;
	Jetz.use({ install(jetzLibrary) { installedPlugin = jetzLibrary; } });
	assert('Jetz.use() installs a plugin', installedPlugin, Jetz);

	// gap fixes: listen() reactive callback child + ListState.asRemember()
	section('listen() and asRemember()');

	const listenCount = stateOf(0);
	const listenBox = div({ id: 'listen-box' }, 'base ', listen(parent => {
		parent.addClass(`seen-${listenCount.value}`);
		parent.text(`base ${listenCount.value}`);
	}));
	mountInto('listen', listenBox);
	assert('listen() callback runs when the parent rendered', textOf('#listen-box'), 'base 0');
	assert('listen() does not render a wrapper node', find('#listen-box').children.length, 0);
	listenCount.value = 3;
	assert('listen() callback re-runs on state change', textOf('#listen-box'), 'base 3');
	assert('listen() callback receives the parent element', find('#listen-box').classList.contains('seen-3'), true);
	let stoppedRuns = 0;
	const stoppedListener = listen(() => stoppedRuns++);
	listenBox.append(stoppedListener);
	stoppedListener.stop();
	const runsAtStop = stoppedRuns;
	listenCount.value = 4;
	assert('stop() unregisters the listener', stoppedRuns, runsAtStop);

	assert('asRemember() marks the list as remembered', lateRememberedList.isRemember, true);
	assert('asRemember() keeps the current values', JSON.stringify(lateRememberedList.values), '["seed"]');
	lateRememberedList.set(['from-phase-1']); // verified after the reload below
	lateRememberedList.push('also-pushed');

	// component lifecycle: onCreate / onMount / onUpdate / onDestroy
	section('component lifecycle');

	// class component
	const classLog = [];
	class LifecycleCard extends Component {
		render() { return div({ id: 'lifecycle-class' }, 'class card'); }
		onCreate() { classLog.push('create'); }
		onMount() { classLog.push('mount'); }
		onUpdate() { classLog.push('update'); }
		onDestroy() { classLog.push('destroy'); }
	}
	mountInto('lifecycle-class-slot', div(LifecycleCard.new()));
	assert('class onCreate runs before render, onMount after attach', classLog.join(','), 'create,mount');

	const lifecycleState = stateOf(0);
	lifecycleState.value = 1;
	assert('class onUpdate runs on state change', classLog.join(','), 'create,mount,update');

	find('#section-lifecycle-class-slot').innerHTML = ''; // simulate external removal
	lifecycleState.value = 2; // sweep runs on triggerByState
	assert('class onDestroy fires when its node is detached', classLog.join(','), 'create,mount,update,destroy');

	// function component with standalone hooks (props via closure)
	const fnLog = [];
	const lifecycleUser = { name: 'Ada' };
	function LifecycleUser() {
		onCreate(() => fnLog.push('create'));
		onMount(() => fnLog.push('mount'));
		onUpdate(() => fnLog.push('update'));
		onDestroy(() => fnLog.push('destroy'));
		return div({ id: 'lifecycle-fn' }, `user ${lifecycleUser.name}`);
	}
	mountInto('lifecycle-fn-slot', div(LifecycleUser));
	assert('function component renders', textOf('#lifecycle-fn'), 'user Ada');
	assert('function onCreate/onMount fire', fnLog.join(','), 'create,mount');

	const fnState = stateOf(0);
	fnState.value = 1;
	assert('function onUpdate fires on state change', fnLog.join(','), 'create,mount,update');

	// remove() path fires onDestroy
	const fnBox = find('#lifecycle-fn').$;
	fnBox.remove();
	fnState.value = 2;
	assert('function onDestroy fires on element.remove()', fnLog.join(','), 'create,mount,update,destroy');

	// landing page + router navigation
	section('landing page & router');

	// render the landing page directly (verifies the home-page.html conversion)
	mountInto('landing-direct-slot', Landing());
	assert('landing renders its root #landing-page', !!find('#section-landing-direct-slot #landing-page'), true);
	assert('landing hero heading is present', textOf('#section-landing-direct-slot #landing-page h1'), 'The marketplace for premium digital assets');
	assert('landing renders all 6 product cards', findAll('#section-landing-direct-slot #product-grid > div').length, 6);
	assert('landing nav has the template links', textOf('#section-landing-direct-slot nav #navbar-sticky ul'), 'DiscoverCategoriesMy Assets');
	assert('landing footer has social links', findAll('#section-landing-direct-slot footer a').length >= 3, true);

	// search filtering (the module-level `products` list is the grid's source of truth)
	const searchInput = find('#section-landing-direct-slot #default-search');
	searchInput.value = 'React';
	searchInput.dispatchEvent(new Event('input', { bubbles: true }));
