	utilitiesBox.setStyle({ color: 'rgb(0, 0, 255)' });
	assert('setStyle() applies styles after render', find('#utils-box').style.color, 'rgb(0, 0, 255)');
	assert('getStyle() reads a style value', utilitiesBox.getStyle('color'), 'rgb(0, 0, 255)');
	utilitiesBox.disable();
